/**
 * Translates a single package benefit string into the requested language
 * If language is 'id', returns original Indonesian string.
 * Falls back to English or original string if key not found.
 */
export function translateBenefit(benefitStr, lang = 'en') {
  if (!benefitStr) return '';
  const clean = String(benefitStr).trim();
  if (lang === 'id') return clean;
  
  const targetDict = BENEFIT_TRANSLATIONS[lang] || BENEFIT_TRANSLATIONS['en'];
  return targetDict?.[clean] || BENEFIT_TRANSLATIONS['en']?.[clean] || clean;
}
