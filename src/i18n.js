let currentLang = localStorage.getItem('lang') || DEFAULT_LANG;

/** Get translation by key */
export function t(key) {
  const translations = TRANSLATIONS[currentLang] || TRANSLATIONS[DEFAULT_LANG];
  return translations[key] ?? TRANSLATIONS[DEFAULT_LANG][key] ?? key;
}

/** Get current language code */
export function getLang() {
  return currentLang;
}

/** Set language and persist */
export function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
}

/** Get all supported languages with metadata */
export function getLanguages() {
  return SUPPORTED_LANGS.map(code => ({
    code,
    name: TRANSLATIONS[code]._lang,
    flag: TRANSLATIONS[code]._flag,
  }));
}

/** Get the date locale string for the current language */
export function getDateLocale() {
  const map = { id: 'id-ID', en: 'en-US', zh: 'zh-CN', ja: 'ja-JP', ru: 'ru-RU', de: 'de-DE' };
  return map[currentLang] || 'en-US';
}

/** Format currency respecting current language */
export function formatCurrencyI18n(amount) {
  return new Intl.NumberFormat(getDateLocale(), {
    style: 'currency',
    currency: 'IDR',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

/** Translate duration strings (e.g. "3 jam" -> "3 hours") */
export function translateDuration(durationStr) {
  if (!durationStr) return '';
  let str = durationStr.toLowerCase();
  str = str.replace('jam', t('time_hours'));
  str = str.replace('menit', t('time_minutes'));
  return str;
}
