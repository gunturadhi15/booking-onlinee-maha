// Supported languages strictly matching user requirements:
// Rusia (ru), Spanyol (es), Itali (it), Prancis (fr), Inggris (en), plus Bahasa Indonesia (id)
export const SUPPORTED_LANGS = ['ru', 'es', 'it', 'fr', 'en', 'id'];
export const DEFAULT_LANG = 'id';

let currentLang = (typeof localStorage !== 'undefined' ? localStorage.getItem('lang') : null) || 'id';
// Default to id or en, fallback if invalid
if (!SUPPORTED_LANGS.includes(currentLang)) {
  currentLang = 'id';
}

/** Get translation by key with full fallback across languages */
export function t(key) {
  const lang = currentLang;
  const dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];
  
  if (dict[key] !== undefined) {
    return dict[key];
  }

  // Fallback to English
  if (TRANSLATIONS.en?.[key] !== undefined) {
    return TRANSLATIONS.en[key];
  }

  // Fallback to Indonesian
  if (TRANSLATIONS.id?.[key] !== undefined) {
    return TRANSLATIONS.id[key];
  }

  return key;
}

/** Get current language code */
export function getLang() {
  return currentLang;
}

/** Set language, persist and apply html lang */
export function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
}

/** Get all supported languages with metadata */
export function getLanguages() {
  return SUPPORTED_LANGS.map(code => ({
    code,
    name: TRANSLATIONS[code]._lang,
    flag: TRANSLATIONS[code]._flag,
  }));
}

/** Get the date locale string for the current language */
export function getDateLocale() {
  const map = {
    ru: 'ru-RU',
    es: 'es-ES',
    it: 'it-IT',
    fr: 'fr-FR',
    en: 'en-US',
    id: 'id-ID'
  };
  return map[currentLang] || 'en-US';
}

/** Format currency respecting current language */
export function formatCurrencyI18n(amount) {
  return new Intl.NumberFormat(getDateLocale(), {
    style: 'currency',
    currency: 'IDR',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

/** Translate duration strings (e.g. "3 jam" -> "3 hours" / "3 horas" / "3 ore" / "3 heures" / "3 часа") */
export function translateDuration(durationStr) {
  if (!durationStr) return '';
  const trimmed = String(durationStr).trim();
  const lower = trimmed.toLowerCase();

  // Full day
  if (lower.includes('hari penuh') || lower.includes('full day') || lower.includes('1 hari')) {
    return t('time_full_day');
  }

  // Number extraction
  const match = trimmed.match(/^([\d\.]+)\s*(jam|hours?|horas?|ore|heures?|часа?|часов|menit|minutes?|minutos?|минут)/i);
  if (match) {
    const num = match[1];
    const unit = match[2].toLowerCase();
    if (unit.startsWith('jam') || unit.startsWith('hour') || unit.startsWith('hora') || unit.startsWith('ore') || unit.startsWith('heur') || unit.startsWith('час')) {
      return `${num} ${t('time_hours')}`;
    }
    if (unit.startsWith('menit') || unit.startsWith('minut') || unit.startsWith('минут')) {
      return `${num} ${t('time_minutes')}`;
    }
  }

  let str = trimmed;
  str = str.replace(/jam/gi, t('time_hours'));
  str = str.replace(/menit/gi, t('time_minutes'));
  return str;
}

