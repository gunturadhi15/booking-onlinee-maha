/**
 * Supabase Client Configuration & Database Services
 * 
 * Membaca variabel lingkungan:
 * - NEXT_PUBLIC_SUPABASE_URL
 * - NEXT_PUBLIC_SUPABASE_ANON_KEY
 */

import { createClient } from '@supabase/supabase-js';

// Helper membaca variabel lingkungan dari import.meta.env (Vite) atau process.env (Vercel/Node fallback)
const getEnvVar = (name) => {
  if (typeof import.meta !== 'undefined' && import.meta.env && import.meta.env[name]) {
    return import.meta.env[name];
  }
  if (typeof process !== 'undefined' && process.env && process.env[name]) {
    return process.env[name];
  }
  return '';
};

export const SUPABASE_URL = getEnvVar('NEXT_PUBLIC_SUPABASE_URL') || getEnvVar('VITE_SUPABASE_URL') || '';
export const SUPABASE_ANON_KEY = getEnvVar('NEXT_PUBLIC_SUPABASE_ANON_KEY') || getEnvVar('VITE_SUPABASE_ANON_KEY') || '';

/**
 * Memeriksa apakah kredensial Supabase sudah dikonfigurasi dengan benar
 */
export const isSupabaseConfigured = () => {
  return Boolean(
    SUPABASE_URL &&
    SUPABASE_ANON_KEY &&
    !SUPABASE_URL.includes('your-project') &&
    !SUPABASE_ANON_KEY.includes('your-anon-key')
  );
};

/**
 * Inisialisasi Supabase JS Client
 */
export const supabase = createClient(
  SUPABASE_URL || 'https://placeholder.supabase.co',
  SUPABASE_ANON_KEY || 'placeholder-anon-key'
);

/**
 * Service: Insert data booking ke tabel `bookings`
 * Sesuai skema:
 * - id (uuid, auto-generated by Supabase gen_random_uuid())
 * - customer_name (text)
 * - customer_phone (text)
 * - customer_email (text)
 * - package_name (text)
 * - tour_date (date)
 * - total_price (numeric/integer)
 * - status (text, default: 'pending')
 * - invoice_number (text)
 * - created_at (timestamp with time zone)
 */
export async function createBookingInSupabase(bookingData) {
  if (!isSupabaseConfigured()) {
    console.warn('⚠️ [Supabase] NEXT_PUBLIC_SUPABASE_URL atau NEXT_PUBLIC_SUPABASE_ANON_KEY belum diisi. Menggunakan mode simulasi lokal.');
    return {
      success: true,
      simulated: true,
      data: {
        id: crypto.randomUUID ? crypto.randomUUID() : `bkg-${Date.now()}`,
        ...bookingData,
        created_at: new Date().toISOString()
      }
    };
  }

  // Exact 100% database schema columns
  const basePayload = {
    customer_name: bookingData.customer_name,
    customer_phone: bookingData.customer_phone || bookingData.whatsapp,
    customer_email: bookingData.customer_email || bookingData.email,
    package_name: bookingData.package_name,
    tour_date: bookingData.tour_date || bookingData.booking_date,
    total_price: Number(bookingData.total_price || bookingData.grand_total || 0),
    status: bookingData.status || 'pending',
    invoice_number: bookingData.invoice_number || bookingData.invoice_id
  };

  // If notes provided, prepare candidate payload
  const hasNotes = Boolean(bookingData.notes);
  const payloadWithNotes = hasNotes ? { ...basePayload, notes: bookingData.notes } : basePayload;

  const tryInsert = async (p) => {
    try {
      const { data, error } = await supabase.from('bookings').insert([p]).select();
      if (!error && data && data.length > 0) {
        return { success: true, data: data[0] };
      }
      const plainInsert = await supabase.from('bookings').insert([p]);
      if (!plainInsert.error) {
        return { success: true, data: { id: `bkg-${Date.now()}`, ...p, created_at: new Date().toISOString() } };
      }
      return { success: false, error: plainInsert.error || error };
    } catch (err) {
      return { success: false, error: err };
    }
  };

  try {
    // 1. Try with notes if provided
    if (hasNotes) {
      const resWithNotes = await tryInsert(payloadWithNotes);
      if (resWithNotes.success) {
        console.log('✅ [Supabase] Data berhasil disimpan (termasuk kolom notes).');
        return resWithNotes;
      }
      // If error was because column 'notes' does not exist in user's schema, retry cleanly with basePayload
      const errMsg = String(resWithNotes.error?.message || '');
      if (errMsg.toLowerCase().includes('notes') || errMsg.toLowerCase().includes('column')) {
        console.warn('ℹ️ [Supabase] Kolom notes belum ada di tabel Supabase. Menyimpan data dengan skema inti murni.');
        const resBase = await tryInsert(basePayload);
        if (resBase.success) return resBase;
      }
    } else {
      const resBase = await tryInsert(basePayload);
      if (resBase.success) return resBase;
    }

    // 2. Fallback to local simulation if Supabase is unreachable/RLS blocked
    console.warn('⚠️ [Supabase Warning]: Gagal insert ke server Supabase, fallback ke mode lokal.');
    return {
      success: true,
      simulated: true,
      data: {
        id: `bkg-${Date.now()}`,
        ...basePayload,
        created_at: new Date().toISOString()
      }
    };
  } catch (err) {
    console.error('❌ [Supabase Network/Unexpected Error]:', err);
    return {
      success: true,
      simulated: true,
      warning: err.message,
      data: {
        id: `bkg-${Date.now()}`,
        ...basePayload,
        created_at: new Date().toISOString()
      }
    };
  }
}

/**
 * Service: Update status booking (misal: 'paid', 'completed', 'cancelled')
 */
export async function updateBookingStatusInSupabase(invoiceNumber, status = 'paid') {
  if (!isSupabaseConfigured()) {
    console.warn('⚠️ [Supabase] Mode simulasi lokal (status diupdate di session).');
    return { success: true, simulated: true };
  }

  try {
    const { error } = await supabase
      .from('bookings')
      .update({ status })
      .eq('invoice_number', invoiceNumber);

    if (error) {
      console.warn('⚠️ [Supabase Update Warning]:', error.message);
      return { success: true, warning: error.message };
    }

    return { success: true };
  } catch (err) {
    console.warn('⚠️ [Supabase Update Error]:', err);
    return { success: true, warning: err.message };
  }
}

/**
 * Service: Ambil detail booking berdasarkan invoice_number
 */
export async function getBookedTimesFromSupabase(tourDate) {
  if (!isSupabaseConfigured() || !tourDate) {
    return [];
  }

  try {
    const { data, error } = await supabase
      .from('bookings')
      .select('tour_date, notes, status')
      .eq('tour_date', tourDate)
      .neq('status', 'cancelled');

    if (error || !data) {
      return [];
    }

    const times = [];
    data.forEach(b => {
      if (b.notes) {
        const timeMatch = b.notes.match(/\[Time:\s*(\d{2}:\d{2})\]/i) || b.notes.match(/(\d{2}:\d{2})\s*WITA/i);
        if (timeMatch) times.push(timeMatch[1]);
      }
    });

    return times;
  } catch (err) {
    console.warn('⚠️ [Supabase] Gagal mengambil slot booking:', err);
    return [];
  }
}

/**
 * Service: Ambil detail booking berdasarkan invoice_number
 */
export async function getBookingByInvoiceFromSupabase(invoiceNumber) {
  if (!isSupabaseConfigured()) {
    return { success: false, simulated: true, data: null };
  }

  try {
    const { data, error } = await supabase
      .from('bookings')
      .select('*')
      .eq('invoice_number', invoiceNumber)
      .maybeSingle();

    if (error) {
      return { success: false, error };
    }

    return { success: true, data };
  } catch (err) {
    return { success: false, error: err };
  }
}

